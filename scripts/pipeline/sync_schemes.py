"""Phase 3.8 - publish validated records to data/schemes.json with version history.

* Changed-field detection against the currently published dataset.
* Every published record gets a monotonically increasing `version`.
* Never overwrites reliable data with worse data: if a record was VERIFIED /
  PARTIALLY_VERIFIED and the new run is SOURCE_UNAVAILABLE (fetch failed) or
  NEEDS_REVIEW only because quotes went missing, the previous version is kept
  and marked with `staleSince`.
* Records that disappear from the source are kept and marked INACTIVE only by
  a reviewer. Here they are retained with a `missingFromLatestRun` flag.
* A dated history snapshot of the diff goes to data/history/.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from safe_fetch import ROOT  # noqa: E402

IN = ROOT / "data" / "build" / "validated.json"
PUBLISHED = ROOT / "data" / "schemes.json"
HISTORY = ROOT / "data" / "history"
TRACKED = ["name", "description", "criteria", "benefits", "documents", "applicationUrl", "infoUrl", "applicationWindow", "status", "jurisdictions", "department"]
GOOD = {"VERIFIED", "PARTIALLY_VERIFIED"}

PUBLIC_KEYS = ["id", "name", "altNames", "description", "category", "subcategory", "level", "jurisdictions", "ministry", "department",
               "implementingAuthority", "targetBeneficiaries", "criteria", "benefits", "documents", "renewal", "applicationProcess",
               "applicationMode", "applicationUrl", "applicationUrlEvidence", "infoUrl", "guidelinesUrl", "governmentOrderRef", "applicationWindow",
               "contact", "status", "sources", "verification", "lastVerified", "extractedAt", "provenance", "version", "staleSince", "missingFromLatestRun"]


def public(rec: dict) -> dict:
    return {k: rec.get(k) for k in PUBLIC_KEYS if k in rec}


def main() -> None:
    stamp = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    new = {r["id"]: r for r in json.loads(IN.read_text(encoding="utf-8"))["records"]}
    old = {}
    if PUBLISHED.exists():
        old = {r["id"]: r for r in json.loads(PUBLISHED.read_text(encoding="utf-8"))["schemes"]}
    out, diff = {}, {"added": [], "changed": {}, "keptPrevious": [], "missingFromLatestRun": []}
    for sid, rec in new.items():
        prev = old.get(sid)
        st = rec["verification"]["status"]
        if prev and prev["verification"]["status"] in GOOD and (st == "SOURCE_UNAVAILABLE" or (st == "NEEDS_REVIEW" and rec["verification"]["missingEvidence"] and not rec.get("needsReview"))):
            kept = dict(prev)
            kept["staleSince"] = prev.get("staleSince") or stamp
            out[sid] = kept
            diff["keptPrevious"].append({"id": sid, "newStatus": st})
            continue
        rec = public(rec)
        if prev is None:
            rec["version"] = 1
            diff["added"].append(sid)
        else:
            changed = [k for k in TRACKED if json.dumps(prev.get(k), sort_keys=True) != json.dumps(rec.get(k), sort_keys=True)]
            rec["version"] = prev.get("version", 1) + (1 if changed else 0)
            if changed:
                diff["changed"][sid] = changed
        rec.pop("staleSince", None)
        out[sid] = rec
    for sid, prev in old.items():
        if sid not in new:
            p = dict(prev)
            p["missingFromLatestRun"] = stamp
            out[sid] = p
            diff["missingFromLatestRun"].append(sid)

    schemes = sorted(out.values(), key=lambda r: (r["level"] != "CENTRAL", r["name"].lower()))
    PUBLISHED.write_text(json.dumps({
        "schemaVersion": 2,
        "generatedAt": stamp,
        "notice": "Generated by scripts/pipeline. Every record is traceable to official sources, and each criterion carries a verbatim evidence quote. Do not edit by hand: edit data/curation/ and re-run the pipeline.",
        "count": len(schemes),
        "schemes": schemes,
    }, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    HISTORY.mkdir(parents=True, exist_ok=True)
    (HISTORY / f"{stamp[:10]}-{stamp[11:19].replace(':', '')}.json").write_text(json.dumps({"syncedAt": stamp, **diff}, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"published {len(schemes)} | added {len(diff['added'])} changed {len(diff['changed'])} keptPrevious {len(diff['keptPrevious'])} missing {len(diff['missingFromLatestRun'])}")


if __name__ == "__main__":
    main()
