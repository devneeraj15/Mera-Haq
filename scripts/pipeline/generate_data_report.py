"""Phase 11 - DATA_QUALITY_REPORT.md, built only from pipeline artefacts.

Every number in the report is computed from data/schemes.json and
data/reports/*. Nothing is typed in by hand.
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from safe_fetch import ROOT  # noqa: E402

PUB = json.loads((ROOT / "data" / "schemes.json").read_text(encoding="utf-8"))
LOG = json.loads((ROOT / "data" / "reports" / "ingest-log.json").read_text(encoding="utf-8"))
DUP = json.loads((ROOT / "data" / "reports" / "duplicates.json").read_text(encoding="utf-8"))
DISC = json.loads((ROOT / "data" / "sources" / "discovered-urls.json").read_text(encoding="utf-8"))
SEEDS = json.loads((ROOT / "data" / "sources" / "seed-urls.json").read_text(encoding="utf-8"))
DOMAINS = json.loads((ROOT / "data" / "sources" / "domains.json").read_text(encoding="utf-8"))["domains"]
LOC = json.loads((ROOT / "data" / "registry" / "locations.json").read_text(encoding="utf-8"))["locations"]
SNAP_COUNT = len(list((ROOT / "data" / "snapshots").glob("*.json")))


def table(rows, head):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    s = PUB["schemes"]
    status = Counter(r["verification"]["status"] for r in s)
    level = Counter(r["level"] for r in s)
    cat = Counter(r["category"] for r in s)
    dept = Counter((r.get("department") or "(not stated)") for r in s)
    no_app = [r["id"] for r in s if not r.get("applicationUrl")]
    no_guide = [r["id"] for r in s if not r.get("guidelinesUrl")]
    no_machine = [r["id"] for r in s if not any(c.get("op") != "manual" for c in r["criteria"])]
    no_docs = [r["id"] for r in s if not r.get("documents")]
    quotes_t = sum(r["verification"]["quotesTotal"] for r in s)
    quotes_f = sum(r["verification"]["quotesFound"] for r in s)
    closed = [r["id"] for r in s if any("window closed" in w for w in r["verification"]["warnings"])]
    central = level.get("CENTRAL", 0)

    geo_rows = []
    for l in LOC:
        own = sum(1 for r in s if l["code"] in r["jurisdictions"])
        geo_rows.append([l["name"], "State" if l["type"] == "STATE" else "Union Territory", own, central, own + central, "State/UT-specific sources ingested" if own else "**No State/UT-specific schemes ingested yet**"])

    failed = LOG.get("failed", [])
    blocked = [d for d in DOMAINS if d["status"] != "ALLOWED"]
    md = f"""# Data Quality Report

> Generated by `scripts/pipeline/generate_data_report.py` from `data/schemes.json` (generated {PUB['generatedAt']}).
> Every number below comes from pipeline outputs. **Nothing here claims nationwide coverage.**

## 1. Summary

| Metric | Value |
|---|---|
| Candidate source URLs (seed pages + listing-discovered + cited) | {len(SEEDS['pages']) + len(DISC)} |
| Scheme pages discovered from listings (MahaDBT) | {len(DISC)} |
| Source snapshots stored | {SNAP_COUNT} |
| Failed source requests (last ingest run) | {len(failed)} |
| Unique published schemes | {len(s)} |
| Central Government schemes | {level.get('CENTRAL', 0)} |
| State Government schemes | {level.get('STATE', 0)} |
| Union Territory schemes | {level.get('UNION_TERRITORY', 0)} |
| Evidence quotes checked / found in source | {quotes_t} / {quotes_f} |
| Duplicate scheme IDs | {len(DUP['sameId'])} |
| Same-name groups (different directorates, kept separate) | {len(DUP['sameName'])} |
| Identical source pages under different URLs | {len(DUP['sameSourceText'])} |

## 2. Verification status

{table(sorted(status.items()), ['Status', 'Records'])}

- **VERIFIED**: human-curated, and every evidence quote was found in the official source snapshot.
- **PARTIALLY_VERIFIED**: every quote was found, but the record was extracted automatically from a structured official page and not reviewed field by field, or it has open review notes. Shown with a visible warning.
- **NEEDS_REVIEW**: in the review queue (`data/reports/review-queue.json`). Shown only with a strong warning and never as a confirmed opportunity.
- Unverified (OUTDATED / SOURCE_UNAVAILABLE): {status.get('OUTDATED', 0) + status.get('SOURCE_UNAVAILABLE', 0)}.

## 3. Schemes by category

{table(sorted(cat.items(), key=lambda x: -x[1]), ['Category', 'Records'])}

## 4. Schemes by department

{table(sorted(dept.items(), key=lambda x: -x[1]), ['Department', 'Records'])}

## 5. Completeness gaps

| Gap | Count | Records |
|---|---|---|
| Missing official application URL (apply offline / at bank) | {len(no_app)} | {', '.join(no_app) or '-'} |
| Missing guidelines URL | {len(no_guide)} | (most records; MahaDBT GR PDFs not ingested) |
| No machine-checkable eligibility criteria | {len(no_machine)} | {', '.join(no_machine) or '-'} |
| No required-documents list | {len(no_docs)} | {', '.join(no_docs) or '-'} |
| Application window closed | {len(closed)} | {', '.join(closed) or '-'} |

## 6. Failed source requests (last ingest run)

{table([[f['url'], f['code']] for f in failed], ['URL', 'Failure']) if failed else 'None.'}

## 7. Sources not machine-ingested (policy / access)

{table([[d['host'], d['status'], d.get('notes', '')] for d in blocked], ['Host', 'Status', 'Reason'])}

## 8. Geographic coverage (all 28 States and 8 Union Territories)

Central schemes ({central}) apply in every State/UT. State/UT-specific coverage currently comes **only from Maharashtra (MahaDBT)**. Every other State/UT has **zero** State-specific schemes ingested. That is a coverage gap, not a statement that those States/UTs have no schemes.

{table(geo_rows, ['State / UT', 'Type', 'State/UT-specific', 'Central', 'Total shown', 'Coverage note'])}
"""
    (ROOT / "DATA_QUALITY_REPORT.md").write_text(md, encoding="utf-8")
    print("wrote DATA_QUALITY_REPORT.md")


if __name__ == "__main__":
    main()
